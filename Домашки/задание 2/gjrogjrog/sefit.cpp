#include <iostream>

int main() {
    // Локализация для корректного вывода кириллицы в консоль (актуально для Windows)
    std::setlocale(LC_ALL, "ru_RU.UTF-8");

    int a, b;
    std::cout << "Введите два целых числа через пробел: ";
    std::cin >> a >> b;

    std::cout << "\nИсходные значения: a = " << a << ", b = " << b << "\n\n";

    // 1. Базовые арифметические операторы
    std::cout << "Арифметические операторы:\n";
    std::cout << "Сложение (+): " << a << " + " << b << " = " << (a + b) << '\n';
    std::cout << "Вычитание (-): " << a << " - " << b << " = " << (a - b) << '\n';
    std::cout << "Умножение (*): " << a << " * " << b << " = " << (a * b) << '\n';

    // 2. Целочисленное деление и остаток
    // Проверка деления на ноль для предотвращения неопределенного поведения
    if (b != 0) {
        std::cout << "Целочисленное деление (/): " << a << " / " << b << " = " << (a / b) << '\n';
        std::cout << "Остаток от деления (%): " << a << " % " << b << " = " << (a % b) << '\n';
    } else {
        std::cout << "Целочисленное деление (/): деление на ноль невозможно\n";
        std::cout << "Остаток от деления (%): деление на ноль невозможно\n";
    }

    // 3. Составное присваивание на копиях
    // Создаем копии, чтобы не изменять исходные a и b для последующих независимых вычислений
    int c_add = a;
    int c_sub = a;
    int c_mul = a;
    int c_div = a;
    int c_mod = a;

    std::cout << "\nСоставное присваивание (на копиях исходного a):\n";

    c_add += b;
    std::cout << "c += b: " << a << " += " << b << " = " << c_add << '\n';

    c_sub -= b;
    std::cout << "c -= b: " << a << " -= " << b << " = " << c_sub << '\n';

    c_mul *= b;
    std::cout << "c *= b: " << a << " *= " << b << " = " << c_mul << '\n';

    if (b != 0) {
        c_div /= b;
        std::cout << "c /= b: " << a << " /= " << b << " = " << c_div << '\n';

        c_mod %= b;
        std::cout << "c %= b: " << a << " %= " << b << " = " << c_mod << '\n';
    } else {
        std::cout << "c /= b: деление на ноль невозможно\n";
        std::cout << "c %= b: деление на ноль невозможно\n";
    }

    return 0;
}