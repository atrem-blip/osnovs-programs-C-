#include <iostream>

int main() {
    // Локализация для корректного вывода кириллицы в консоль
    std::setlocale(LC_ALL, "ru_RU.UTF-8");

    int x, y;
    std::cout << "Введите два целых числа (x и y) через пробел: ";
    std::cin >> x >> y;

    std::cout << "\nИсходные значения: x = " << x << ", y = " << y << "\n\n";

    // 1. Операторы сравнения
    std::cout << "Операторы сравнения:\n";
    std::cout << "x == y: " << std::boolalpha << (x == y) << '\n';
    std::cout << "x != y: " << (x != y) << '\n'; // boolalpha сохраняется в потоке
    std::cout << "x < y:  " << (x < y) << '\n';
    std::cout << "x > y:  " << (x > y) << '\n';
    std::cout << "x <= y: " << (x <= y) << '\n';
    std::cout << "x >= y: " << (x >= y) << '\n';

    // 2. Логические операторы
    std::cout << "\nлогические операторы:\n";
    // Скобки вокруг сравнений обязательны из-за более высокого приоритета операторов сравнения
    std::cout << "(x > 0) && (y > 0): " << ((x > 0) && (y > 0)) << '\n';
    std::cout << "(x > 0) || (y > 0): " << ((x > 0) || (y > 0)) << '\n';
    std::cout << "!(x == y):          " << (!(x == y)) << '\n';

    // Возвращаем числовой формат вывода для bool, чтобы не влиять на дальнейшую работу программы
    std::cout << std::noboolalpha;

    return 0;
}