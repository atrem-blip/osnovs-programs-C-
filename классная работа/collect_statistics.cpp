#include <iostream>

int main() {
    // ---------- 1. Ввод и валидация ----------
    int n;
    std::cout << "Введите количество чисел N (1..100): ";
    if (!(std::cin >> n)) {
        std::cout << "Ошибка: введено не целое число.\n";
        return 1;
    }
    if (n <= 0 || n > 100) {
        std::cout << "Ошибка: N должно быть в диапазоне от 1 до 100.\n";
        return 1;
    }

    // ---------- 2. Сбор статистики (в одном проходе по вводу) ----------
    int positives = 0;   // количество положительных
    int negatives = 0;   // количество отрицательных
    int zeros     = 0;   // количество нулей
    long long sum = 0;   // сумма всех чисел (long long, чтобы не переполнить int)
    int mn = 0;          // минимальное значение
    int mx = 0;          // максимальное значение
    int even = 0;        // количество чётных
    int odd  = 0;        // количество нечётных

    for (int i = 0; i < n; ++i) {
        int x;
        std::cout << "Число " << (i + 1) << ": ";
        if (!(std::cin >> x)) {
            std::cout << "Ошибка: введено не целое число.\n";
            return 1;
        }

        if (i == 0) {
            mn = mx = x; // минимум и максимум инициализируем первым числом
        } else {
            if (x < mn) mn = x;
            if (x > mx) mx = x;
        }

        sum += x;

        // Знак числа
        if (x > 0)      ++positives;
        else if (x < 0) ++negatives;
        else            ++zeros;

        // Чётность (для отрицательных тоже верно: -4 % 2 == 0)
        if (x % 2 == 0) ++even;
        else            ++odd;
    }

    // Пока статистика просто собрана; вывод отчёта будет в следующем пункте.
    return 0;
}
