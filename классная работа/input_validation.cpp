#include <iostream>

int main() {
    // ----- Ввод и валидация N -----
    int n;
    std::cout << "Введите количество чисел N (1..100): ";
    if (!(std::cin >> n)) {                 // защита от ввода не числа
        std::cout << "Ошибка: введено не целое число.\n";
        return 1;
    }
    if (n <= 0 || n > 100) {                // N <= 0 или N > 100 -> ошибка и выход
        std::cout << "Ошибка: N должно быть в диапазоне от 1 до 100.\n";
        return 1;
    }

    // ----- Ввод N чисел в цикле for -----
    for (int i = 0; i < n; ++i) {
        int x;
        std::cout << "Число " << (i + 1) << ": ";
        if (!(std::cin >> x)) {             // проверяем, что введено целое число
            std::cout << "Ошибка: введено не целое число.\n";
            return 1;
        }
        // пока здесь просто читаем число;
        // сбор статистики и анализ добавим на следующих шагах
    }

    std::cout << "Числа успешно введены.\n";
    return 0;
}
