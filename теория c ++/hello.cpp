// Это директива препроцессора. Она сообщает компилятору:
// "Подключи библиотеку iostream (input/output stream)".
// Без неё мы не сможем выводить текст на экран или читать ввод.
#include <iostream>

// int main() — это главная функция. С неё начинается выполнение ЛЮБОЙ программы на C++.
// int означает, что функция вернёт целое число (код завершения) операционной системе.
int main() {
    // std::cout — это объект, представляющий стандартный поток вывода (обычно консоль).
    // Оператор << ("положить в поток") отправляет текст в этот поток.
    // std::endl — означает "конец строки" и заодно сбрасывает буфер вывода (заставляет текст появиться немедленно).
    std::cout << "Привет мир!" << std::endl;

    // return 0; — сообщает операционной системе, что программа завершилась успешно.
    // Ноль традиционно означает "без ошибок". Любое другое число — код ошибки.
    return 0;
}